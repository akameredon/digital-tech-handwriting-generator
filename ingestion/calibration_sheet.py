"""Optional fixed-layout handwriting calibration worksheet.

Only pages generated by this module are accepted here. Character labels come
from worksheet cell positions, never from guessed positions on an arbitrary
notebook page. Natural-page handwriting still requires a real HTR provider.
"""
from __future__ import annotations

from io import BytesIO
import warnings
from pathlib import Path
from typing import Any, Dict, List, Tuple

import cv2
import numpy as np
from PIL import Image, UnidentifiedImageError
from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

from ingestion.preprocessor import DEFAULT_SAMPLE_ROWS

PAGE_WIDTH, PAGE_HEIGHT = landscape(A4)
GRID_LEFT = 35.0
GRID_RIGHT = PAGE_WIDTH - 35.0
GRID_TOP = 520.0
GRID_BOTTOM = 35.0
GRID_COLUMNS = 15
GRID_ROWS = len(DEFAULT_SAMPLE_ROWS)
CELL_WIDTH = (GRID_RIGHT - GRID_LEFT) / GRID_COLUMNS
CELL_HEIGHT = (GRID_TOP - GRID_BOTTOM) / GRID_ROWS
MAX_IMAGE_BYTES = 12 * 1024 * 1024
MAX_IMAGE_PIXELS = 12_000_000
MAX_IMAGE_SIDE = 6000


class CalibrationSheetError(ValueError):
    """The uploaded image is not a usable copy of the calibration sheet."""


def _row_start(row: int) -> int:
    return (GRID_COLUMNS - len(DEFAULT_SAMPLE_ROWS[row])) // 2


def write_calibration_sheet(output_path: str | Path) -> Path:
    """Create an A4 worksheet with one labeled cell per supported character."""
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    pdf = canvas.Canvas(str(output), pagesize=(PAGE_WIDTH, PAGE_HEIGHT))
    pdf.setTitle("Optional Handwriting Calibration Sheet")
    pdf.setFillColor(HexColor("#17253A"))
    pdf.setFont("Helvetica-Bold", 13)
    pdf.drawString(35, PAGE_HEIGHT - 27, "Optional handwriting calibration")
    pdf.setFillColor(HexColor("#526174"))
    pdf.setFont("Helvetica", 8)
    pdf.drawString(35, PAGE_HEIGHT - 42,
                   "Write each printed character once in its box. Use dark ink; do not add marks outside the boxes.")
    pdf.drawString(35, PAGE_HEIGHT - 54,
                   "Scan this page upright as a full-page JPG/PNG. This sheet is optional; ordinary page recognition is separate.")

    # Four corner dot codes preserve orientation and reject unrelated page photos.
    _draw_dot_code(pdf, 8 * mm, PAGE_HEIGHT - 8 * mm, 1)
    _draw_dot_code(pdf, PAGE_WIDTH - 8 * mm, PAGE_HEIGHT - 8 * mm, 2)
    _draw_dot_code(pdf, PAGE_WIDTH - 8 * mm, 8 * mm, 3)
    _draw_dot_code(pdf, 8 * mm, 8 * mm, 4)

    pdf.setStrokeColor(HexColor("#AEB8C7"))
    pdf.setLineWidth(0.55)
    for column in range(GRID_COLUMNS + 1):
        x = GRID_LEFT + column * CELL_WIDTH
        pdf.line(x, GRID_BOTTOM, x, GRID_TOP)
    for row in range(GRID_ROWS + 1):
        y = GRID_TOP - row * CELL_HEIGHT
        pdf.line(GRID_LEFT, y, GRID_RIGHT, y)

    for row_index, row_chars in enumerate(DEFAULT_SAMPLE_ROWS):
        row_top = GRID_TOP - row_index * CELL_HEIGHT
        row_bottom = row_top - CELL_HEIGHT
        start = _row_start(row_index)
        for offset, character in enumerate(row_chars):
            column = start + offset
            left = GRID_LEFT + column * CELL_WIDTH
            right = left + CELL_WIDTH
            pdf.setFillColor(HexColor("#566274"))
            pdf.setFont("Helvetica-Bold", 8)
            pdf.drawCentredString((left + right) / 2, row_top - 12, character)

    pdf.setFillColor(HexColor("#69778A"))
    pdf.setFont("Helvetica", 7)
    pdf.drawRightString(PAGE_WIDTH - 35, 18, "D. Lesson Studio · Worksheet v1")
    pdf.save()
    return output


def _draw_dot_code(pdf: canvas.Canvas, center_x: float, center_y: float, count: int) -> None:
    """Draw a corner marker with a unique number of disconnected dots."""
    radius = 0.8 * mm
    spacing = 2.6 * mm
    if count == 1:
        points = [(center_x, center_y)]
    elif count == 2:
        points = [(center_x - spacing / 2, center_y), (center_x + spacing / 2, center_y)]
    elif count == 3:
        points = [(center_x - spacing, center_y), (center_x, center_y), (center_x + spacing, center_y)]
    else:
        points = [
            (center_x - spacing / 2, center_y - spacing / 2),
            (center_x + spacing / 2, center_y - spacing / 2),
            (center_x - spacing / 2, center_y + spacing / 2),
            (center_x + spacing / 2, center_y + spacing / 2),
        ]
    pdf.setFillColor(HexColor("#111827"))
    for x, y in points:
        pdf.circle(x, y, radius, stroke=0, fill=1)


def extract_calibration_glyphs(image_bytes: bytes) -> Tuple[List[Dict[str, Any]], List[str]]:
    """Validate the generated worksheet and return only ink from labeled cells."""
    if not image_bytes or len(image_bytes) > MAX_IMAGE_BYTES:
        raise CalibrationSheetError("Upload a JPG or PNG calibration-sheet scan smaller than 12 MB.")
    try:
        # Pillow checks its global pixel threshold while opening, before our
        # stricter dimensions check can run. Promote the warning to an error so
        # oversized/decompression-bomb images become a controlled client error.
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(BytesIO(image_bytes)) as decoded:
                if decoded.format not in {"JPEG", "PNG"}:
                    raise CalibrationSheetError("Upload a JPG or PNG calibration-sheet scan.")
                source_width, source_height = decoded.size
                if (
                    source_width < 1
                    or source_height < 1
                    or source_width > MAX_IMAGE_SIDE
                    or source_height > MAX_IMAGE_SIDE
                    or source_width * source_height > MAX_IMAGE_PIXELS
                ):
                    raise CalibrationSheetError(
                        "The scan dimensions are too large. Export a JPG or PNG with no more than 12 megapixels."
                    )
                rgb = np.asarray(decoded.convert("RGB"))
    except CalibrationSheetError:
        raise
    except (Image.DecompressionBombError, Image.DecompressionBombWarning) as exc:
        raise CalibrationSheetError(
            "This image exceeds the safe size limit. Resize it to no more than 12 megapixels and upload it again."
        ) from exc
    except (OSError, ValueError, UnidentifiedImageError) as exc:
        raise CalibrationSheetError("We could not read this image. Upload a clear JPG or PNG scan.") from exc
    image = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)

    height, width = image.shape[:2]
    if width < height:
        image = cv2.rotate(image, cv2.ROTATE_90_CLOCKWISE)
        height, width = image.shape[:2]
    ratio = width / height
    expected_ratio = PAGE_WIDTH / PAGE_HEIGHT
    if abs(ratio - expected_ratio) > 0.075:
        raise CalibrationSheetError(
            "This does not look like the full landscape worksheet. Scan the whole page without cropping."
        )
    if height < 850:
        raise CalibrationSheetError("The scan is too small. Use a full-resolution document scan.")
    if max(width, height) > 2800:
        scale = 2800 / max(width, height)
        image = cv2.resize(image, (round(width * scale), round(height * scale)), interpolation=cv2.INTER_AREA)
        height, width = image.shape[:2]

    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    dark = cv2.threshold(gray, 95, 255, cv2.THRESH_BINARY_INV)[1]
    _validate_orientation_codes(dark)
    _validate_grid(gray)

    glyphs: List[Dict[str, Any]] = []
    missing: List[str] = []
    for row_index, row_chars in enumerate(DEFAULT_SAMPLE_ROWS):
        row_top = GRID_TOP - row_index * CELL_HEIGHT
        row_bottom = row_top - CELL_HEIGHT
        start = _row_start(row_index)
        for offset, character in enumerate(row_chars):
            column = start + offset
            cell_left = GRID_LEFT + column * CELL_WIDTH
            cell_right = cell_left + CELL_WIDTH
            # Exclude the printed label and the grid border, retaining the writer's ink only.
            x0 = int(round((cell_left + CELL_WIDTH * 0.13) / PAGE_WIDTH * width))
            x1 = int(round((cell_right - CELL_WIDTH * 0.13) / PAGE_WIDTH * width))
            y0 = int(round((PAGE_HEIGHT - row_top + CELL_HEIGHT * 0.24) / PAGE_HEIGHT * height))
            y1 = int(round((PAGE_HEIGHT - row_bottom - CELL_HEIGHT * 0.10) / PAGE_HEIGHT * height))
            crop = gray[y0:y1, x0:x1]
            if crop.size == 0:
                missing.append(character)
                continue
            binary = cv2.threshold(crop, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)[1]
            # Remove isolated scan specks but preserve punctuation and detached dots.
            ink_pixels = int(cv2.countNonZero(binary))
            if ink_pixels < max(5, int(binary.size * 0.00008)):
                missing.append(character)
                continue
            if ink_pixels > int(binary.size * 0.30):
                raise CalibrationSheetError(
                    f"The box for {character!r} contains too much ink. Use one clear character per box."
                )
            glyphs.append({
                "label": character,
                "image": binary,
                "row": row_index + 1,
                "bbox": (x0, y0, x1 - x0, y1 - y0),
                "label_source": "worksheet_cell_teacher_confirmation_required",
            })

    if len(glyphs) < 8:
        raise CalibrationSheetError("Too few handwritten characters were found. Fill more labeled boxes and scan again.")
    return glyphs, missing


def _validate_orientation_codes(dark: np.ndarray) -> None:
    height, width = dark.shape
    expected = ((1, 1), (1, 2), (2, 3), (2, 4))  # top-left, top-right, bottom-right, bottom-left
    patches = (
        (0.012, 0.012, 0.040, 0.055),
        (0.960, 0.012, 0.988, 0.055),
        (0.960, 0.945, 0.988, 0.988),
        (0.012, 0.945, 0.040, 0.988),
    )
    for (x0f, y0f, x1f, y1f), (_, expected_count) in zip(patches, expected):
        x0, x1 = int(x0f * width), int(x1f * width)
        y0, y1 = int(y0f * height), int(y1f * height)
        region = dark[y0:y1, x0:x1]
        count, _, stats, _ = cv2.connectedComponentsWithStats(region, connectivity=8)
        dot_count = sum(
            1 for x, y, w, h, area in stats[1:]
            if area >= 4 and area <= max(30, int(region.size * 0.03)) and 0.45 <= w / max(h, 1) <= 2.2
        )
        if dot_count != expected_count:
            raise CalibrationSheetError(
                "The worksheet is rotated, cropped, or not the generated calibration sheet. "
                "Scan it upright with all four corners visible."
            )


def _validate_grid(gray: np.ndarray) -> None:
    height, width = gray.shape
    dark = cv2.threshold(gray, 225, 255, cv2.THRESH_BINARY_INV)[1]
    x0 = GRID_LEFT / PAGE_WIDTH * width
    x1 = GRID_RIGHT / PAGE_WIDTH * width
    y0 = (PAGE_HEIGHT - GRID_TOP) / PAGE_HEIGHT * height
    y1 = (PAGE_HEIGHT - GRID_BOTTOM) / PAGE_HEIGHT * height
    band_x = max(2, int(width * 0.0025))
    band_y = max(2, int(height * 0.0035))

    for index in range(GRID_COLUMNS + 1):
        x = int(round((GRID_LEFT + index * CELL_WIDTH) / PAGE_WIDTH * width))
        strip = dark[int(y0):int(y1), max(0, x - band_x):min(width, x + band_x + 1)]
        if strip.size == 0 or cv2.countNonZero(strip) / strip.size < 0.07:
            raise CalibrationSheetError("The worksheet grid is missing or distorted. Scan the generated sheet flat and upright.")
    for index in range(GRID_ROWS + 1):
        y = int(round((PAGE_HEIGHT - (GRID_TOP - index * CELL_HEIGHT)) / PAGE_HEIGHT * height))
        strip = dark[max(0, y - band_y):min(height, y + band_y + 1), int(x0):int(x1)]
        if strip.size == 0 or cv2.countNonZero(strip) / strip.size < 0.07:
            raise CalibrationSheetError("The worksheet grid is missing or distorted. Scan the generated sheet flat and upright.")
